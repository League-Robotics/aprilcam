#!/usr/bin/env python3
"""Generate ``clasi/usecases.md`` from ``docs/design/use-cases/*.md``
(ticket 036-001, issue
``get-use-case-coverage-reports-zero-reads-the-wrong-file.md``).

CLASI's ``get_use_case_coverage()`` MCP tool (implemented outside this
repo, in the installed ``clasi`` package's
``clasi/tools/process_tools.py``) reads ``clasi/usecases.md`` and
parses lines matching ``##\\s+(UC-\\d+):\\s*(.+)`` to build its
``total_use_cases`` count. This project never populated that file --
the real use cases live in ``docs/design/use-cases/*.md`` (currently
``daemon.md`` and ``cli.md``), each with headings like
``### UC-01 -- Start the daemon and configure it``. Without this
index, the tool always reported zero, so several sprint exit criteria
that treat it as a traceability audit passed vacuously.

Fixing the tool itself (pointing it at ``docs/design/use-cases/``
directly) is out of scope here -- that code lives in a different
repository (see sprint 036's plan for the follow-up issue). This
script instead generates a ``clasi/usecases.md`` index in the exact
format the existing tool already parses.

Run from the project root:

    uv run python scripts/generate_usecases_index.py

``tests/test_usecases_index.py`` independently re-parses
``docs/design/use-cases/*.md`` and asserts the committed
``clasi/usecases.md`` still matches, so a use case added, renamed, or
removed without regenerating the index fails that test instead of
silently drifting back to matching nothing.
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Dict, List, Tuple

import re

PROJECT_ROOT = Path(__file__).resolve().parent.parent
USE_CASES_DIR = PROJECT_ROOT / "docs" / "design" / "use-cases"
OUTPUT_FILE = PROJECT_ROOT / "clasi" / "usecases.md"

#: Matches a real use-case heading, e.g.
#: "### UC-01 -- Start the daemon and configure it". Source headings
#: use an em dash ("--" below stands in for U+2014); a plain hyphen is
#: also accepted so a future heading typed with "-" still gets indexed.
_HEADING_RE = re.compile(r"^###\s+(UC-\d+)\s*[—-]\s*(.+?)\s*$")

#: Files under docs/design/use-cases/ that are not sources of real UC
#: entries. README.md is the authoring template -- its own
#: "### UC-nn -- <goal, phrased as the actor's outcome>" heading is a
#: placeholder, not a use case. The two *-interface-trace.md files are
#: generated traceability artifacts that reference UC ids; they do not
#: define new ones.
_EXCLUDED_NAMES = frozenset({"README.md"})
_EXCLUDED_SUFFIXES = ("-interface-trace.md",)


def _is_source_file(path: Path) -> bool:
    if path.name in _EXCLUDED_NAMES:
        return False
    if path.name.endswith(_EXCLUDED_SUFFIXES):
        return False
    return True


def discover_use_cases(use_cases_dir: Path = USE_CASES_DIR) -> List[Tuple[str, str]]:
    """Parse every ``### UC-NN -- Title`` heading from the source files
    in *use_cases_dir*, returning ``(uc_id, title)`` pairs sorted in
    ascending numeric order by the UC number.

    Excludes ``README.md`` (the authoring template) and
    ``*-interface-trace.md`` files -- see the module docstring.
    """
    entries: Dict[str, str] = {}
    for path in sorted(use_cases_dir.glob("*.md")):
        if not _is_source_file(path):
            continue
        for line in path.read_text().splitlines():
            match = _HEADING_RE.match(line)
            if not match:
                continue
            uc_id, title = match.group(1), match.group(2)
            if uc_id in entries and entries[uc_id] != title:
                raise ValueError(
                    f"{uc_id} appears with conflicting titles: "
                    f"{entries[uc_id]!r} vs {title!r} (in {path})"
                )
            entries[uc_id] = title
    return sorted(entries.items(), key=lambda item: int(item[0].split("-")[1]))


def render_usecases_md(entries: List[Tuple[str, str]]) -> str:
    """Render *entries* as the ``clasi/usecases.md`` index content.

    Each entry becomes ``## UC-NN: Title`` -- matching the
    ``##\\s+(UC-\\d+):\\s*(.+)`` regex that CLASI's
    ``get_use_case_coverage()`` (installed outside this repo) parses.
    """
    lines = [
        "# Use Case Index",
        "",
        "Generated by `scripts/generate_usecases_index.py` from "
        "`docs/design/use-cases/*.md` -- do not hand-edit. Regenerate "
        "after adding, renaming, or removing a use case:",
        "",
        "```",
        "uv run python scripts/generate_usecases_index.py",
        "```",
        "",
    ]
    for uc_id, title in entries:
        lines.append(f"## {uc_id}: {title}")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    entries = discover_use_cases()
    if not entries:
        print(
            "No UC-NN headings found under "
            f"{USE_CASES_DIR.relative_to(PROJECT_ROOT)} -- aborting "
            "without writing an empty index.",
            file=sys.stderr,
        )
        return 1
    OUTPUT_FILE.write_text(render_usecases_md(entries))
    print(f"Wrote {len(entries)} use cases to {OUTPUT_FILE.relative_to(PROJECT_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
