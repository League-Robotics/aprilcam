logger = logging.getLogger(__name__)

#: Default bound for WorkerBackend.open() to wait for the child to
#: *connect* to the control channel before giving up and raising --
#: an implementation-time choice, not an architectural one (camera-
#: DESIGN.md's Open Questions names this explicitly as left to a
#: ticket to decide). The child connects before it imports cv2 or
#: touches the camera (``capture_worker.main``), so this only has to
#: cover interpreter start-up plus the ``aprilcam``/``numpy`` imports.
DEFAULT_STARTUP_TIMEOUT = 10.0

#: Default bound, counted from the moment the child connected, for it
#: to open the camera and report its first frame. Separate from
#: :data:`DEFAULT_STARTUP_TIMEOUT` because the two failures mean
#: different things (a child that never connects died or could not
#: import; a connected child that never reports a frame is the camera
#: itself misbehaving), and because a real AVFoundation session can
#: legitimately take several seconds to deliver its first frame after
#: a respawn, particularly right after the host wakes from sleep.
DEFAULT_READY_TIMEOUT = 30.0

#: How many trailing lines of the child's stderr are kept for inclusion
#: in a ``WorkerStartupError`` message. Every line is also logged as it
#: arrives, so the daemon log carries the full text.
_STDERR_TAIL_LINES = 20

#: Default bound for a single control-channel round trip
#: (get_property/set_property/settable_names/frame_size).
DEFAULT_CONTROL_TIMEOUT = 3.0

#: Default grace period between SIGTERM and SIGKILL in close().
DEFAULT_CLOSE_GRACE = 3.0

#: Default bound WorkerBackend.read() waits for a new frame to appear
#: in the ring before reporting "nothing new" -- mirrors a real
#: camera's read() blocking briefly rather than returning instantly on
#: every call, without ever blocking indefinitely if the worker has
#: stalled or died.
DEFAULT_READ_TIMEOUT = 1.0

#: Poll interval while WorkerBackend.read() waits out DEFAULT_READ_TIMEOUT
#: for a fresh sequence number.
_READ_POLL_INTERVAL = 0.005

#: How often _read_ready polls the connection while also watching for
#: the child exiting early -- bounds handshake-detection latency
#: without a tight busy loop.
_READY_POLL_INTERVAL = 0.2


def _popen_spawn_kwargs() -> Dict[str, Any]:
    """Keyword arguments that make ``subprocess.Popen`` spawn the worker
    through ``posix_spawn`` rather than ``fork``+``exec`` on macOS.

    The daemon is a large multi-threaded process with AVFoundation,
    CoreMedia and cv2 loaded (its start-up camera probe runs OpenCV
    in-process). Forking such a process on macOS runs every registered
    ``pthread_atfork`` child handler and the Objective-C runtime's
    fork-safety checks inside the forked copy *before* ``exec`` -- and
    those can abort the child in a few milliseconds with nothing the
    parent can observe except a zombie (seen 2026-09-05: every respawn
    after the host slept failed with "did not connect", the child dead
    within 100 ms, no crash report, while the identical command from a
    fresh process worked). ``posix_spawn`` never runs any of that: the
    kernel creates the new image directly.

    CPython uses ``posix_spawn`` only when ``close_fds`` is false (no
    ``closefrom`` support on macOS), no ``cwd``, no ``preexec_fn`` and no
    ``pass_fds`` -- all of which ``open()`` already satisfies. Leaving
    ``close_fds`` false is safe here because every file descriptor
    Python itself creates is non-inheritable by default (PEP 446), so
    the worker inherits only the standard streams the daemon was
    launched with. Elsewhere the default (``close_fds=True``) is kept.
    """
    if sys.platform == "darwin":
        return {"close_fds": False}
    return {}


class WorkerStartupError(RuntimeError):
    """The capture worker child process failed to start, connect, or
    report its first frame within the startup timeout -- raised by
    :meth:`WorkerBackend.open`, matching ``CaptureBackend.open()``'s
    "raises on failure, never a sentinel" contract."""


class WorkerBackend(CaptureBackend):
    """A :class:`CaptureBackend` backed by a per-camera
    ``capture_worker.py`` child process instead of an in-process
    ``cv2.VideoCapture``.

    Parameters mirror
    :class:`~aprilcam.camera.backends.opencv_backend.OpenCVBackend`'s
    real-camera constructor arguments (*index*/*width*/*height*/
    *backend*) plus *synthetic*, the test-only escape hatch that makes
    the spawned worker use a fake frame source
    (``capture_worker.SyntheticBackend``) instead of opening real
    hardware -- see that module's ``--synthetic WxH@fps`` flag. Exactly
    one of *index*/*synthetic* must be given.

    *index_resolver* and *expected_hardware_key* (sprint 039 ticket 003)
    are the identical additive, optional contract
    :class:`~aprilcam.camera.backends.opencv_backend.OpenCVBackend`
    has -- see this module's docstring's "Identity-safe reopen" section
    for the full mechanism and why post-open verification is done here
    (parent-side, via :func:`~aprilcam.camera.identity.resolve_identity`)
    rather than inside the spawned child. Both default to ``None``,
    preserving every existing direct ``WorkerBackend(index)``/
    ``WorkerBackend(synthetic=...)`` construction's behaviour exactly.
    """

    def __init__(
        self,
        index: Optional[int] = None,
        *,
        width: Optional[int] = None,
        height: Optional[int] = None,
        backend: Optional[int] = None,
        synthetic: Optional[str] = None,
        index_resolver: Optional[Callable[[], Optional[int]]] = None,
        expected_hardware_key: Optional[str] = None,
        startup_timeout: float = DEFAULT_STARTUP_TIMEOUT,
        ready_timeout: float = DEFAULT_READY_TIMEOUT,
        control_timeout: float = DEFAULT_CONTROL_TIMEOUT,
        close_grace: float = DEFAULT_CLOSE_GRACE,
        read_timeout: float = DEFAULT_READ_TIMEOUT,
        ring_slots: int = DEFAULT_RING_SLOTS,
    ) -> None:
        if index is None and synthetic is None:
            raise ValueError("WorkerBackend requires either index or synthetic")
        self._index = index
        self._width = width
        self._height = height
        self._backend_id = backend
        self._synthetic = synthetic
        self._index_resolver = index_resolver
        self._expected_hardware_key = expected_hardware_key
        self._startup_timeout = startup_timeout
        self._ready_timeout = ready_timeout
        self._control_timeout = control_timeout
        self._close_grace = close_grace
        self._read_timeout = read_timeout
        self._ring_slots = ring_slots

        self._process: "Optional[subprocess.Popen[bytes]]" = None
        self._control: Optional[ControlChannel] = None
        self._ring: Optional[FrameRing] = None
        #: Trailing stderr lines of the most recently spawned child --
        #: the diagnostic every startup failure message ends with.
        self._stderr_tail: Deque[str] = deque(maxlen=_STDERR_TAIL_LINES)

    # -- CaptureBackend ---------------------------------------------------

    @property
    def is_open(self) -> bool:
        return self._process is not None and self._process.poll() is None

    def open(self) -> None:
        """Spawn (or respawn) the capture worker child process.

        **Fresh re-resolution, every call (sprint 039).** When
        *index_resolver* is set, it is called here -- unconditionally,
        before the spawn command is built, on *every* :meth:`open`
        including a self-heal/stall-triggered respawn that closes and
        reopens this exact object -- and :attr:`_index` is updated to
        whatever it returns. ``None`` (hardware key not currently
        enumerated) raises :class:`~aprilcam.camera.backends.
        CameraNotEnumeratedError` immediately, before anything is
        spawned -- never a stale index. See this module's docstring's
        "Identity-safe reopen" section.
        """
        if self.is_open:
            return
        if self._index_resolver is not None:
            resolved = self._index_resolver()
            if resolved is None:
                raise CameraNotEnumeratedError(
                    f"camera hardware key is not currently enumerated "
                    f"(last known index {self._index})"
                )
            self._index = resolved

        listener = Listener()
        process: "Optional[subprocess.Popen[bytes]]" = None
        self._stderr_tail.clear()
        try:
            # stderr is piped, never discarded: a child that dies before
            # it can connect has *only* its stderr to say why (a
            # traceback from an import failure, an interpreter that could
            # not start), and the whole point of the respawn path is that
            # the daemon keeps running long after anyone was watching a
            # terminal. Every line goes to the daemon log via _drain_stderr.
            process = subprocess.Popen(
                self._build_command(str(listener.address)),
                stdout=subprocess.DEVNULL,
                stderr=subprocess.PIPE,
                **_popen_spawn_kwargs(),
            )
            self._start_stderr_drain(process)
            conn = self._accept(listener, process)
            ready = self._read_ready(conn, process)
        finally:
            listener.close()

        if not ready.get("ok", False):
            self._terminate(process)
            raise WorkerStartupError(
                f"capture worker failed to start: {ready.get('error') or 'no detail reported'}"
                f"{self._stderr_suffix()}"
            )

        shape: Tuple[int, ...] = tuple(ready["shape"])
        dtype = ready["dtype"]
        try:
            ring = FrameRing.attach(ready["ring_name"], shape, dtype, num_slots=self._ring_slots)
        except Exception:
            self._terminate(process)
            conn.close()
            raise

        self._process = process
        self._control = ControlChannel(conn)
        self._ring = ring

        # Post-open identity verification (sprint 039) -- parent-side,
        # after the child has reported its first frame: see this
        # module's docstring's "Post-open identity verification" section
        # for why this runs here rather than inside the worker. Runs
        # after self._process/_control/_ring are all assigned so a
        # mismatch can tear the worker down via the ordinary close()
        # path rather than duplicating its cleanup.
        index = self._index
        if (
            self._expected_hardware_key is not None
            and index is not None
            and self._can_verify_identity()
        ):
            observed = resolve_identity(index)
            if observed.hardware_key != self._expected_hardware_key:
                pid = process.pid
                self.close()
                logger.warning(
                    "WorkerBackend: post-open identity mismatch at index %d "
                    "(worker pid %s) -- expected hardware_key %r, observed %r; "
                    "refusing to keep this worker running (killing it rather "
                    "than silently serving a different physical camera's "
                    "frames)",
                    index,
                    pid,
                    self._expected_hardware_key,
                    observed.hardware_key,
                )
                raise RuntimeError(
                    f"post-open identity mismatch at index {index}: expected "
                    f"hardware_key {self._expected_hardware_key!r}, observed "
                    f"{observed.hardware_key!r}"
                )

    def _can_verify_identity(self) -> bool:
        """Whether this platform/*expected_hardware_key* combination can
        be checked post-open (sprint 039) -- identical restriction to
        :meth:`~aprilcam.camera.backends.opencv_backend.OpenCVBackend.
        _can_verify_identity`: only macOS AVFoundation's ``uniqueID``
        tier is reliable enough to re-resolve per-index after the fact,
        never a fallback tier (``vidpid``/``loc``/``name``) that can
        legitimately change value across a re-enumeration for reasons
        unrelated to a substitution bug. Also requires a real *index*
        (``None`` only when this backend is *synthetic*-only, which
        never carries a meaningful hardware identity to check)."""
        return (
            self._index is not None
            and sys.platform == "darwin"
            and (self._expected_hardware_key or "").startswith("avf:")
        )

    def read(self) -> Optional[np.ndarray]:
        if not self.is_open or self._ring is None:
            return None
        deadline = time.monotonic() + self._read_timeout
        while True:
            record = self._ring.read_latest()
            if record is not None:
                return record.frame
            if not self.is_open:
                return None
            if time.monotonic() >= deadline:
                return None
            time.sleep(_READ_POLL_INTERVAL)

    def close(self) -> None:
        self._terminate(self._process)
        if self._control is not None:
            try:
                self._control.close()
            except Exception:  # noqa: BLE001 -- shutdown must not raise
                pass
            self._control = None
        if self._ring is not None:
            # Always attempt unlink, regardless of which side "owns" the
            # segment: a gracefully-exited worker already unlinked it
            # itself (this becomes a harmlessly-swallowed
            # FileNotFoundError, per FrameRing.close()'s own docstring),
            # but a SIGKILLed worker never got the chance to -- and this
            # is the only remaining side that can still do it, per the
            # "no leaked shared-memory segment" acceptance criterion.
            self._ring.close(unlink=True)
            self._ring = None
        self._process = None

    def frame_size(self) -> Optional[Tuple[int, int]]:
        result = self._request("frame_size")
        if result is None:
            return None
        return (int(result[0]), int(result[1]))

    def heartbeat_age(self) -> Optional[float]:
        """Seconds since the shared-memory ring's last published frame
        (sprint 038 ticket 005) -- ``camera.camera.Camera.check_stall``'s
        stall-detection primitive, see
        ``CaptureBackend.heartbeat_age``'s docstring for the full
        contract this overrides.

        Uses :meth:`~aprilcam.camera.backends._frame_ring.FrameRing.peek`
        -- a cheap ``(sequence, timestamp)`` snapshot, no frame copy --
        rather than :meth:`~aprilcam.camera.backends._frame_ring.
        FrameRing.read_latest`, so calling this on a fixed interval from
        a background watchdog never disturbs
        :meth:`WorkerBackend.read`'s own "seen" bookkeeping (the two
        methods are independent by design -- see ``peek``'s own
        docstring). The ring header's ``timestamp`` is written with
        ``time.time()`` (``_frame_ring.py``'s ``publish``, wall-clock,
        not ``time.monotonic()``), which is what makes a child-process
        timestamp comparable against this parent process's own
        ``time.time()`` call here -- both processes' wall clocks agree
        (unlike ``time.monotonic()``'s per-process-arbitrary epoch).

        ``None`` when not currently open (nothing to report, matching
        the base class default for "no heartbeat available right now")
        -- never raises, mirroring every other ``CaptureBackend``
        method's "only ``open()`` raises" discipline.
        """
        if self._ring is None:
            return None
        _, timestamp = self._ring.peek()
        return max(0.0, time.time() - timestamp)

    # -- ControlBackend-shaped surface (duck-typed, mirrors OpenCVBackend) --

    def get_property(self, name: str) -> Optional[float]:
        result = self._request("get_property", {"name": name})
        return None if result is None else float(result)

    def set_property(self, name: str, value: float) -> bool:
        result = self._request("set_property", {"name": name, "value": value})
        return bool(result) if result is not None else False

    def settable_names(self) -> Set[str]:
        result = self._request("settable_names")
        return set(result) if result else set()

    def describe_set_failure(self, name: str, value: float) -> Optional[str]:
        # Not part of the control channel's wire protocol --
        # ``_control_channel.py``'s ``_METHODS`` is deliberately a
        # closed set of four (that module's own docstring: "not an
        # open-ended RPC mechanism"), so there is nothing to proxy this
        # through. Matches ``ControlBackend.describe_set_failure``'s own
        # default rather than inventing wire support ticket 003
        # deliberately did not provide.
        return None

    # -- diagnostics, useful to callers/tests beyond the CaptureBackend
    # surface (mirrors OpenCVBackend exposing .index) --------------------

    @property
    def pid(self) -> Optional[int]:
        """The child process's pid, or ``None`` if not currently open."""
        return self._process.pid if self._process is not None else None

    @property
    def ring_name(self) -> Optional[str]:
        """The attached FrameRing's shared-memory segment name, or
        ``None`` if not currently open."""
        return self._ring.name if self._ring is not None else None

    # -- internals ---------------------------------------------------------

    def _build_command(self, control_address: str) -> List[str]:
        cmd = [
            sys.executable,
            "-m",
            "aprilcam.camera.capture_worker",
            "--control-address",
            control_address,
            "--ring-slots",
            str(self._ring_slots),
        ]
        if self._synthetic is not None:
            cmd += ["--synthetic", self._synthetic]
        else:
            cmd += ["--index", str(self._index)]
            if self._width is not None:
                cmd += ["--width", str(self._width)]
            if self._height is not None:
                cmd += ["--height", str(self._height)]
            if self._backend_id is not None:
                cmd += ["--backend", str(self._backend_id)]
        return cmd

    def _start_stderr_drain(self, process: "subprocess.Popen[bytes]") -> None:
        """Copy the child's stderr into the log (and the tail buffer)
        until the pipe closes -- i.e. until the child exits. Daemon
        thread: it can never keep the parent alive, and it costs nothing
        while the child is quiet."""
        pipe = process.stderr
        if pipe is None:  # pragma: no cover - Popen was given stderr=PIPE
            return
        label = f"capture_worker[index={self._index} pid={process.pid}]"
        tail = self._stderr_tail

        def _drain() -> None:
            try:
                for raw in iter(pipe.readline, b""):
                    line = raw.decode("utf-8", errors="replace").rstrip()
                    if not line:
                        continue
                    tail.append(line)
                    logger.warning("%s: %s", label, line)
            except Exception:  # noqa: BLE001 -- a broken pipe at shutdown is not an error
                pass
            finally:
                try:
                    pipe.close()
                except Exception:  # noqa: BLE001
                    pass

        threading.Thread(target=_drain, name=f"{label} stderr", daemon=True).start()

    def _stderr_suffix(self) -> str:
        """The child's trailing stderr lines, formatted for appending to
        a ``WorkerStartupError`` message -- empty when it said nothing.
        Waits briefly for the drain thread to catch up, since the child
        usually writes its traceback in the same instant it exits."""
        deadline = time.monotonic() + 0.5
        while not self._stderr_tail and time.monotonic() < deadline:
            time.sleep(0.02)
        if not self._stderr_tail:
            return " (worker stderr: empty)"
        return " (worker stderr: " + " | ".join(self._stderr_tail) + ")"

    def _exit_suffix(self, process: "subprocess.Popen[bytes]") -> str:
        code = process.poll()
        if code is None:
            return ""
        return f"; the worker process exited with code {code}"

    def _accept(self, listener: Listener, process: "subprocess.Popen[bytes]") -> Connection:
        result: Dict[str, Any] = {}

        def _accept_target() -> None:
            try:
                result["conn"] = listener.accept()
            except Exception as exc:  # noqa: BLE001 -- reported via result, not raised in this thread
                result["error"] = exc

        thread = threading.Thread(target=_accept_target, daemon=True)
        thread.start()
        # Wait in short slices so a child that dies before connecting is
        # reported at once, with its exit code, instead of after the
        # full connect timeout has elapsed with nothing to show for it.
        deadline = time.monotonic() + self._startup_timeout
        while "conn" not in result and "error" not in result:
            remaining = deadline - time.monotonic()
            if remaining <= 0:
                break
            thread.join(min(remaining, _READY_POLL_INTERVAL))
            if "conn" not in result and process.poll() is not None:
                # Give a connect that raced the exit one more slice.
                thread.join(_READY_POLL_INTERVAL)
                break
        if "conn" not in result:
            self._terminate(process)
            detail = f" ({result['error']})" if "error" in result else ""
            raise WorkerStartupError(
                f"capture worker did not connect to the control channel within "
                f"{self._startup_timeout}s{detail}{self._exit_suffix(process)}"
                f"{self._stderr_suffix()}"
            )
        conn: Connection = result["conn"]
        return conn

    def _read_ready(self, conn: Connection, process: "subprocess.Popen[bytes]") -> Dict[str, Any]:
        deadline = time.monotonic() + self._ready_timeout
        while True:
            remaining = deadline - time.monotonic()
            if remaining <= 0:
                self._terminate(process)
                conn.close()
                raise WorkerStartupError(
                    f"capture worker did not report its first frame within {self._ready_timeout}s"
                    f"{self._stderr_suffix()}"
                )
            if conn.poll(min(remaining, _READY_POLL_INTERVAL)):
                try:
                    payload: Dict[str, Any] = json.loads(conn.recv_bytes().decode("utf-8"))
                except (EOFError, OSError) as exc:
                    # poll() also wakes for a closed connection: the child
                    # connected and then died before its handshake.
                    self._terminate(process)
                    conn.close()
                    raise WorkerStartupError(
                        f"capture worker closed the control channel before reporting its "
                        f"first frame ({exc!r}){self._exit_suffix(process)}{self._stderr_suffix()}"
                    ) from None
                return payload
            if process.poll() is not None:
                conn.close()
                raise WorkerStartupError(
                    f"capture worker exited (code {process.returncode}) before reporting its first frame"
                    f"{self._stderr_suffix()}"
                )

    def _request(self, method: str, params: Optional[Dict[str, Any]] = None) -> Any:
        if not self.is_open or self._control is None:
            return None
        try:
            return self._control.request(method, params, timeout=self._control_timeout)
        except (ControlError, ControlTimeout, OSError, EOFError):
            return None

    def _terminate(self, process: "Optional[subprocess.Popen[bytes]]") -> None:
        if process is None:
            return
        if process.poll() is None:
            process.terminate()
            try:
                process.wait(timeout=self._close_grace)
            except subprocess.TimeoutExpired:
                process.kill()
                process.wait(timeout=self._close_grace)

    def __repr__(self) -> str:  # pragma: no cover - diagnostics only
        status = "open" if self.is_open else "closed"
        return f"WorkerBackend(index={self._index}, {status})"


def default_worker_backend_factory(index: int) -> WorkerBackend:
    """The plain ``backend_factory``-shaped constructor ticket 005 wires
    into ``resolve_capture_backend`` in place of ``OpenCVBackend`` when
    the worker-process backend is config/env-enabled -- kept here, next
    to the class it constructs, rather than duplicated at each call
    site."""
    return WorkerBackend(index)
